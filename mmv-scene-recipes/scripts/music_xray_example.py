#!/usr/bin/env python3
"""Music X-Ray for Magic Music Visuals: three scenes that show what Magic hears, from live audio only.

    python3 music_xray_example.py OUT.magic [--audio-device NAME] [--audio-file PATH] [--syphon NAME] [--size 1920x1080] [--probe PORT]

Scenes (playlist order):
  Pulse    beat orbit + who's playing + drop radar (concepts A, E, D)
  Terrain  endless spectral terrain over an endless song river (concepts B, C)
  Tempo    tempo lens (concept G)

All analysis lives in Globals (one analysis bank shared by the scenes); the shaders only draw.
The shader sources in ../assets/isf/music-xray-src use TEXT(p, o, s, "LABEL") for labels; this script expands it
with a 3x5 bitmap font and writes the finished .fs files to ../assets/isf (referenced by absolute path).
Design, tuning and what was verified live: ../references/music-xray.md.
State codes: 0 intro (also silence), 2 buildup, 3 drop, 4 breakdown (1 is unused: there is no 'groove' in a song;
a steady beat part is named by where it sits, as in the EDM analysis).
Event codes (river pins): 1 drop, 2 lift, 3 buildup, 4 breakdown, 5 beat in, 6 intro (a new track in a mix).
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "assets", "isf", "music-xray-src")
OUT_ISF = os.path.join(HERE, "..", "assets", "isf")
SKILLS = os.path.abspath(os.path.join(HERE, "..", ".."))

# 3x5 glyphs, rows top to bottom
