def bits(ch):
    rows = FONT[ch].split()
    return sum(int(rows[r][c]) << ((4 - r) * 3 + (2 - c)) for r in range(5) for c in range(3))


def font_glsl():
    digits = "\n".join("\tif (d < %d.5) return %d.0;" % (i, bits(str(i))) for i in range(9))
    return """
// 3x5 bitmap font (generated by build_xray.py). Glyph cell = 3x5 units of size s px, advance 4 units.
float glyph(vec2 p, vec2 o, float s, float g) {
	vec2 q = (p - o) / s;
	if (q.x < 0.0 || q.y < 0.0 || q.x >= 3.0 || q.y >= 5.0) return 0.0;
	float idx = floor(q.y) * 3.0 + (2.0 - floor(q.x));
	// +0.5 keeps the quotient clear of an integer: GPU pow(2, n) is not exact (measured: bits 0 and 1 swapped)
	return mod(floor((g + 0.5) / pow(2.0, idx)), 2.0);
}
float digitBits(float d) {
%s
	return %d.0;
}
float p10(float k) { return k < 0.5 ? 1.0 : k < 1.5 ? 10.0 : k < 2.5 ? 100.0 : k < 3.5 ? 1000.0 : k < 4.5 ? 10000.0 : k < 5.5 ? 100000.0 : 1000000.0; }
// v with `dec` decimals (0..2), left-aligned at o; returns coverage
float num(vec2 p, vec2 o, float s, float v, float dec) {
	float r = 0.0, x = 0.0;
	if (v < 0.0) { r += glyph(p, o, s, %d.0); x += 4.0; }
	float iv = floor(abs(v) * p10(dec) + 0.5);
	float ip = floor(iv / p10(dec) + 0.0001);
	float n = 1.0;
	for (int i = 1; i < 7; i++) { if (ip >= p10(float(i))) n += 1.0; }
	for (int i = 0; i < 7; i++) {
		if (float(i) >= n) break;
		float d = mod(floor(ip / p10(n - 1.0 - float(i)) + 0.0001), 10.0);
		r += glyph(p, o + vec2(x * s, 0.0), s, digitBits(d)); x += 4.0;
	}
	if (dec > 0.5) {
		r += glyph(p, o + vec2(x * s, 0.0), s, %d.0); x += 4.0;
		for (int i = 0; i < 2; i++) {
			if (float(i) >= dec) break;
			float d = mod(floor(iv / p10(dec - 1.0 - float(i)) + 0.0001), 10.0);
			r += glyph(p, o + vec2(x * s, 0.0), s, digitBits(d)); x += 4.0;
		}
	}
	return min(r, 1.0);
}
""" % (digits, bits("9"), bits("-"), bits("."))


def _split_args(s):
    """Split a call's argument text on top-level commas."""
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "," and depth == 0:
            out.append(cur.strip()); cur = ""
            continue
        depth += (ch == "(") - (ch == ")")
        cur += ch
    out.append(cur.strip())
    return out


def expand_text(src):
    """TEXT(p, origin, cell, "LABEL") -> sum of glyph() calls (arguments may hold nested calls)."""
    out, i = "", 0
    while True:
        j = src.find("TEXT(", i)
        if j < 0:
            return out + src[i:]
        depth, k = 0, j + 4
        while True:
            depth += (src[k] == "(") - (src[k] == ")")
            if depth == 0:
                break
            k += 1
        p, o, s, label = _split_args(src[j + 5:k])
        label = label.strip('"').upper()
        parts = ["glyph(%s, (%s) + vec2(%d.0 * (%s), 0.0), %s, %d.0)" % (p, o, 4 * n, s, s, bits(ch))
                 for n, ch in enumerate(label) if ch != " "]
        out += src[i:j] + ("min(1.0, " + " + ".join(parts) + ")" if parts else "0.0")
        i = k + 1


def assemble_shaders():
    os.makedirs(OUT_ISF, exist_ok=True)
    paths = {}
    for name in ("XRayPulse", "XRayTerrain", "XRayTempo"):
        with open(os.path.join(SRC, name + ".fs")) as f:
            src = f.read()
        src = expand_text(src.replace("// @FONT", font_glsl()))
        out = os.path.join(OUT_ISF, name + ".fs")
        with open(out, "w") as f:
            f.write(src)
        paths[name] = out
    return paths


def add_globals(b, audio_bank, src="Source 0"):
    """The live analysis. Every Global reads the previous frame's values, so edge detectors use lag Globals."""
    audio_bank.add_audio_bank(b, source=src, kick_decay=0.12, kick_threshold=0.6)
    g = b.glob
    FR = "audio:%s:Freq. Range:" % src
    tau = lambda beats: "(1 - exp(-Dt*max(Bpm, 60)/%g))" % (60 * beats)   # EMA step with a time constant in beats

    # tuning knobs (manual): tempo octave, sub-bass levels for low/back, brightness rise, lift crash, silence
    g("TempoLo", 90)
    g("SubLow", 0.3)
    g("SubHigh", 0.55)
    g("RiseMin", 0.06)
    g("LiftAir", 1.5)
    g("Quiet", 0.02)

    # snare/clap (1.2-5 kHz) and hats (5-20 kHz): onset = rise above the band's own recent average.
    # Measured in Magic: with a 0.4 s average a 16th-note roll lifts the average and hides its own hits.
    for name, rng, decay in (("Snare", "1.2k-5k Hz", 0.1), ("Hat", "5k-20k Hz", 0.05)):
        g(name + "Raw", 0, FR + rng, [("Expression", "x*Gain*4")])
        g(name + "Avg", 0, "calc", [("Expression", "y + (%sRaw - y)*(1 - exp(-Dt/0.15))" % name)])
        g(name, 0, "calc", [("Expression", "max(clamp((%sRaw - %sAvg*1.1)*8, 0, 1), y*exp(-Dt/%g))" % (name, name, decay))])
        g(name + "Gate", 0, "global:" + name, [("Threshold", 0.3)])
        g(name + "GateLag", 0, "calc", [("Expression", name + "Gate")])
        g(name + "Pulse", 0, "calc", [("Expression", "if (%sGate > 0.5 and %sGateLag < 0.5, 1, 0)" % (name, name))])
    for name in ("Kick", "Snare", "Hat"):
        g(name + "Count", 0, "calc", [("Expression", "y + %sPulse" % name)])

    # tempo: interval between kicks, folded into one tempo octave, smoothed with outlier rejection
    g("KickPulseLag", 0, "calc", [("Expression", "KickPulse")])
    g("LastKickT", 0, "calc", [("Expression", "if (KickPulse > 0.5, Time, y)")])
    g("Ioi", 0, "calc", [("Expression", "if (KickPulse > 0.5, Time - LastKickT, y)")])
    g("BpmFold", 0, "calc", [("Expression",
      "if (KickPulse > 0.5 and Time - LastKickT > 0.2 and Time - LastKickT < 2, "
      "(60/(Time - LastKickT)) / pow(2, floor(log(60/(Time - LastKickT)/TempoLo)/log(2))), y)")])
    g("BpmMiss", 0, "calc", [("Expression", "if (KickPulseLag > 0.5, if (abs(BpmFold - Bpm) < Bpm*0.06, 0, y + 1), y)")])
    # a new tempo is taken only when several intervals in a row agree with each other
    # (measured in Magic: snare-roll hits in a buildup made scattered intervals and pulled Bpm to 131.8)
    g("BpmFoldLag", 0, "calc", [("Expression", "if (KickPulseLag > 0.5, BpmFold, y)")])
    g("BpmAgree", 0, "calc", [("Expression", "if (KickPulseLag > 0.5, if (abs(BpmFold - BpmFoldLag) < BpmFold*0.03, y + 1, 0), y)")])
    g("Bpm", 120, "calc", [("Expression",
      "if (y < 1, 120, if (KickPulseLag > 0.5 and BpmFold > 1, "
      "if (abs(BpmFold - y) < y*0.06, y + (BpmFold - y)*0.2, if (BpmMiss >= 3 and BpmAgree >= 3, BpmFold, y)), y))")])

    # beat clock: runs on Bpm, each kick pulls it 35 % towards the nearest beat; 0..4 beats.
    # KickPulse arrives Latency seconds after the kick (envelope, gate and lag Globals, one frame each),
    # so the beat it marks is Latency*Bpm/60 beats behind the clock.
    g("Latency", 0.04)
    err = lambda v: "(round(%s - Latency*Bpm/60) + Latency*Bpm/60 - %s)" % (v, v)
    g("Phase", 0, "calc", [("Expression",
      "frac((y + Dt*Bpm/60 + if (KickPulse > 0.5, 0.35*%s, 0))/4)*4" % err("y"))])
    g("Nudge", 0, "calc", [("Expression", "if (KickPulse > 0.5, %s, y)" % err("Phase"))])
    g("SinceKick", 0, "calc", [("Expression", "(Time - LastKickT)*Bpm/60")])       # beats since the last detected kick
    g("VisualLead", 0.06)                                                        # seconds the drawn beat runs ahead
    g("Lock", 0, "calc", [("Expression",
      "if (KickPulse > 0.5, y*0.75 + 0.25*(1 - min(1, abs(%s)*5)), "
      "if (Time - LastKickT > 120/max(Bpm, 60), y*exp(-Dt/1.2), y))" % err("Phase"))])

    # bar grid: bar 1 is a guess (DownSlot 0) until a drop sets it
    g("BeatInBar", 0, "calc", [("Expression", "floor((Phase - DownSlot) - 4*floor((Phase - DownSlot)/4))")])
    g("BeatLag", 0, "calc", [("Expression", "BeatInBar")])
    g("BeatPulse", 0, "calc", [("Expression", "if (abs(BeatInBar - BeatLag) > 0.5, 1, 0)")])
    g("BarPulse", 0, "calc", [("Expression", "if (BeatInBar < 0.5 and BeatLag > 2.5, 1, 0)")])

    # levels over a beat / a bar / four bars
    g("ToneRaw", 0, "audio:%s:Tone" % src)
    # sub-bass relative to the loudest sub of the last minutes, so SubLow/SubHigh fit any song and gain
    # (the EDM analysis numbers are relative per track too: 0.2 before a drop, 0.76 after)
    g("BassPeak", 0, "calc", [("Expression", "max(Bass, y*exp(-Dt/120), 0.05)")])
    g("SubBeat", 0, "calc", [("Expression", "y + (Bass/max(BassPeak, 0.05) - y)*" + tau(1))])
    g("SubFast", 0, "calc", [("Expression", "y + (Bass/max(BassPeak, 0.05) - y)*" + tau(0.25))])
    g("SubBar", 0, "calc", [("Expression", "y + (Bass/max(BassPeak, 0.05) - y)*" + tau(2))])
    g("VolSlow", 0, "calc", [("Expression", "y + (Volume - y)*(1 - exp(-Dt/2))")])
    # both start at the current brightness (calc Globals load as 0), so the first bars show no false rise
    g("ToneBar", 0, "calc", [("Expression", "if (y < 0.001, ToneRaw, y + (ToneRaw - y)*%s)" % tau(4))])
    g("ToneSlow", 0, "calc", [("Expression", "if (y < 0.001, ToneRaw, y + (ToneRaw - y)*%s)" % tau(16))])
    g("ToneRise", 0, "calc", [("Expression", "ToneBar - ToneSlow")])
    g("AirBeat", 0, "calc", [("Expression", "y + (HatRaw - y)*" + tau(0.25))])
    g("AirBar", 0, "calc", [("Expression", "y + (HatRaw - y)*" + tau(4))])
    g("KickRate", 0, "calc", [("Expression", "y*exp(-Dt*max(Bpm, 60)/240) + KickPulse")])     # about kicks per bar
    g("SnareRate", 0, "calc", [("Expression", "y*exp(-Dt*max(Bpm, 60)/240) + SnarePulse")])  # about snares per bar
    g("SubOut", 0, "calc", [("Expression", "if (BarPulse > 0.5, if (SubBar < SubLow, y + 1, 0), y)")])

    # drop: sub-bass back after >= 2 low bars, checked every frame on a quarter-beat average
    # (on beat lines with a one-beat average it fired 1-2 beats late: seen on real songs); lift: crash a beat into a bar, >= 4 bars into a drop
    g("DropPulse", 0, "calc", [("Expression",
      "if (SubFast > SubHigh and SubOut >= 2 and abs(State - 3) > 0.5 and y < 0.5, 1, 0)")])
    g("LiftBars", 0, "calc", [("Expression", "if (LiftPulse > 0.5 or DropPulse > 0.5, 0, if (BarPulse > 0.5, y + 1, y))")])
    g("LiftPulse", 0, "calc", [("Expression",
      "if (BeatPulse > 0.5 and abs(BeatInBar - 1) < 0.5 and abs(State - 3) < 0.5 and LiftBars >= 4 "
      "and AirBeat > AirBar*LiftAir, 1, 0)")])
    g("DownSlot", 0, "calc", [("Expression", "if (DropPulse > 0.5, round(Phase - 0.25) - 4*floor(round(Phase - 0.25)/4), y)")])
    g("DownSet", 0, "calc", [("Expression", "if (DropPulse > 0.5, 1, y)")])
    g("BarsSinceDrop", 0, "calc", [("Expression", "if (DropPulse > 0.5, 0, if (BarPulse > 0.5, y + 1, y))")])

    # live section state, decided on bar lines (a drop switches at once). A drop lasts while the kick runs;
    # 16 bars of kick without sub-bass after it read as the next track's intro (DJ mix); kickless stays intro
    # before anything happened, else breakdown
    g("ThinBars", 0, "calc", [("Expression", "if (BarPulse > 0.5, if (SubBar < SubLow and KickRate >= 2.5, y + 1, 0), y)")])
    g("BeatOn", 0, "calc", [("Expression", "if (BarPulse > 0.5, if (KickRate >= 2.5, 1, 0), y)")])
    g("BeatOnLag", 0, "calc", [("Expression", "BeatOn")])
    g("State", 0, "calc", [("Expression",
      "if (DropPulse > 0.5, 3, if (BarPulse > 0.5, "
      "if (VolSlow < Quiet, 0, "
      "if (ThinBars >= 16 and y > 0.5, 0, "
      "if (abs(y - 3) < 0.5, if (SubBar < SubLow and KickRate < 0.5, 4, 3), "
      "if (SubBar < SubLow and (ToneRise > RiseMin or SnareRate >= 5), 2, "
      "if (SubBar < SubLow and KickRate < 0.5 and y > 0.5 and abs(y - 2) > 0.5, 4, y))))), y))")])
    g("StateLag", 0, "calc", [("Expression", "State")])
    g("StateBars", 0, "calc", [("Expression", "if (abs(State - StateLag) > 0.5, 0, if (BarPulse > 0.5, y + 1, y))")])
    g("Tension", 0, "calc", [("Expression",
      "if (DropPulse > 0.5, 1, "
      "if (abs(State - 2) < 0.5 or abs(State - 4) < 0.5, "
      "(0.1 + 0.3*min(1, SubOut/4) + 0.3*clamp(ToneRise/0.15, 0, 1) + 0.3*min(1, SnareRate/16))*if (abs(State - 4) < 0.5, 0.6, 1), "
      "if (abs(State - 3) < 0.5, max(0.15, y*exp(-Dt/3)), y*exp(-Dt/1))))")])
    g("DropFlash", 0, "calc", [("Expression", "if (DropPulse > 0.5, 1, y*exp(-Dt/0.6))")])
    g("LiftFlash", 0, "calc", [("Expression", "if (LiftPulse > 0.5, 1, y*exp(-Dt/0.6))")])

    # history ticks for the endless terrain (rows) and river (columns)
    g("TerrainTick", 0, "calc", [("Expression", "if (frac(Time/0.08) < frac(TimeLag/0.08), 1, 0)")])
    g("RiverTick", 0, "calc", [("Expression", "if (frac(Time/0.4) < frac(TimeLag/0.4), 1, 0)")])
    # river pin: first event since the last river column, cleared by the tick
    g("EventCode", 0, "calc", [("Expression",
      "if (RiverTick > 0.5, 0, if (y > 0.5, y, if (DropPulse > 0.5, 1, if (LiftPulse > 0.5, 2, "
      "if (abs(State - StateLag) > 0.5, if (abs(State - 2) < 0.5, 3, if (abs(State - 4) < 0.5, 4, if (State < 0.5, 6, 0))), "
      "if (BeatOn > 0.5 and BeatOnLag < 0.5 and State < 0.5, 5, 0))))))")])
    return b


def link(names):
    return {n: ("global:" + n, [], 0) for n in names}


PULSE = ["Phase", "DownSlot", "DownSet", "Lock", "Bpm", "Nudge", "SinceKick", "VisualLead", "Bass", "HatRaw",
         "KickCount", "SnareCount", "HatCount", "State", "StateBars", "BarsSinceDrop", "Tension", "SubOut",
         "ToneRise", "SnareRate", "DropFlash", "LiftFlash", "Energy", "SubBar"]
TERRAIN = ["Energy", "EnergySlow", "Bass", "State", "EventCode", "TerrainTick", "RiverTick", "Kick", "SubLow"]
TEMPO = ["KickPulseLag", "Ioi", "KickCount", "Bpm", "Lock", "TempoLo"]


PROBE = ["Bass", "SubBar", "SubBeat", "SubOut", "KickRaw", "Kick", "KickCount", "SnareRaw", "SnareAvg", "SnareCount",
         "HatCount", "ToneRaw", "ToneRise", "SnareRate", "KickRate", "Bpm", "Lock", "Phase", "DownSlot", "State",
         "DropPulse", "LiftPulse", "BarsSinceDrop", "EnergySlow", "HatRaw", "AirBar"]


def build(skills, syphon, size, audio_device, probe_port=None, audio_files=None):
    sys.path.insert(0, os.path.join(skills, "mmv-core", "scripts"))
    sys.path.insert(0, os.path.join(skills, "mmv-audio-reactivity", "scripts"))
    import audio_bank
    import magicproj as m
    isf = assemble_shaders()
    b = m.Builder(syphon=syphon, size=size, audio_device=audio_device)
    add_globals(b, audio_bank)

    s, t, g = b.scene("Pulse"), b.scene("Terrain"), b.scene("Tempo")
    vals = link(TERRAIN)
    vals.update({"Source": "layer:Source 0", "Gain": 0.5})
    # flashes read the audio band on the param itself: no Global hops (each Global step is one frame late)
    live = lambda band, expr: ("audio:Source 0:Freq. Range:" + band, [("Expression", expr), ("Clamp", 1)], 0)
    pv = link(PULSE)
    pv.update({"KickLive": live("80-320 Hz", "max(x*Gain*4, y*exp(-Dt/0.12))"),
               "SnareLive": live("1.2k-5k Hz", "max(clamp((x*Gain*4 - SnareAvg*1.1)*8, 0, 1), y*exp(-Dt/0.1))"),
               "HatLive": live("5k-20k Hz", "max(clamp((x*Gain*4 - HatAvg*1.1)*8, 0, 1), y*exp(-Dt/0.05))")})
    shown = [(s, s.node("XRayPulse", pv, isf=isf["XRayPulse"])),
             (t, t.node("XRayTerrain", vals, isf=isf["XRayTerrain"])),
             (g, g.node("XRayTempo", link(TEMPO), isf=isf["XRayTempo"]))]
    probe = None
    if probe_port:      # tuning aid: every PROBE Global sent as /xray/<Name> (OSCSender sends on change)
        probe = b.scene("Probe")
        probe.output(*[probe.node("OSCSender", {"IP Addr.": "127.0.0.1", "Port": str(probe_port), "Message": "/xray/" + n,
                                                "Value": ("global:" + n, [], 0)}) for n in PROBE])
    for scene, node in shown:
        scene.output(node, *([scene.scene_module(probe)] if probe else []))
    root = b.build()
    for path in audio_files or ():
        root = m.add_audio(root, path, source="Source 0", loop=True)
    root = m.set_playlist(root, names=["Pulse", "Terrain", "Tempo"], seconds=3600)
    return m, root


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--syphon", default="MusicXRay")
    ap.add_argument("--size", default="1920x1080")
    ap.add_argument("--audio-device", default=os.environ.get("MMV_AUDIO_DEVICE"))
    ap.add_argument("--probe", type=int, metavar="PORT", help="also send the key Globals as OSC /xray/<Name> to 127.0.0.1:PORT")
    ap.add_argument("--audio-file", action="append", help="play this file into Source 0 (Shift+Cmd+Space in Magic); repeatable")
    a = ap.parse_args()
    w, h = (int(v) for v in a.size.lower().split("x"))
    m, root = build(SKILLS, a.syphon, (w, h), a.audio_device, a.probe, a.audio_file)
    problems = m.check(root, HERE)
    for level, msg in problems:
        print(level, msg)
    m.write(a.out, root)
    print("wrote", a.out)


if __name__ == "__main__":
    main()
