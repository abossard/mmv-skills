#!/usr/bin/env python3
"""Regenerates references/module-catalog.md from magic_modules_v3.json plus the ISF headers shipped in the app.

    python3 gen_catalog.py > catalog.tmp && mv catalog.tmp ../references/module-catalog.md

Needs Magic installed (MAGIC_APP, default MagicBeta.app or Magic.app): without it the script exits 1 instead of
writing a catalog without ranges and options (hence the tmp file: a plain redirect would empty the committed catalog).
Shader description text is deliberately not copied. Per module: category, whether it has an input pin (Bypass), the exact
param names Magic 3 saves with their defaults, ISF ranges (MIN..MAX) and, for `long` params, the option list. A
`long` param is stored as the 0-based INDEX of the option, not the VALUES entry (verified live with Blend).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import magicproj  # noqa: E402

APP = magicproj.MAGIC_APP
MACOS = os.path.join(APP, "Contents/MacOS")


def isf_header(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            found = magicproj.isf_header(f.read())
    except (OSError, ValueError):
        return {}
    return found[0] if found else {}


def pname(i):
    n = i.get("LABEL") or i["NAME"]
    return n[:1].upper() + n[1:]


def main():
    if not os.path.isdir(MACOS):
        sys.exit("Magic app not found at %s; set MAGIC_APP" % APP)
    with open(os.path.join(HERE, "magic_modules_v3.json"), encoding="utf-8") as f:
        data = json.load(f)
    mods = data["modules"]
    by_cat = {}
    for name, m in mods.items():
        by_cat.setdefault(m["category"], []).append(name)
    print("# Module catalog (Magic %s)\n" % data["magic"])
    print("Generated by scripts/gen_catalog.py from `magic_modules_v3.json` (params Magic itself saved) and the ISF headers in the app.")
    print("`pin` = has an input pin (so a Bypass param). `long` options: stored value = 0-based index of the option.\n")
    for cat in sorted(by_cat):
        print("## %s\n" % cat)
        for name in sorted(by_cat[cat], key=str.lower):
            m = mods[name]
            ps = m["params"]
            pin = "pin" if "Bypass" in ps else "no pin"
            h = isf_header(os.path.join(MACOS, m["category"], name + ".fs"))     # Kaleidoscope.fs and Posterize.fs also exist in Modules2/Stylize
            print("- **%s** (%s)" % (name, pin))        # no DESCRIPTION text: it is the shader authors' / Magic's prose
            shown = ["%s=%s" % (k, v) for k, v in ps.items() if k not in ("Bypass", "Power")]
            if shown:
                print("  - params: " + ", ".join(shown))
            for i in h.get("INPUTS", []):
                if i.get("TYPE") == "long" and i.get("LABELS"):
                    print("  - %s options: %s" % (pname(i), ", ".join("%d %s" % (k, l) for k, l in enumerate(i["LABELS"]))))
            ranges = ["%s %s..%s" % (pname(i), i["MIN"], i["MAX"]) for i in h.get("INPUTS", [])
                      if i.get("TYPE") == "float" and "MIN" in i and "MAX" in i]
            if ranges:
                print("  - ranges: " + ", ".join(ranges[:8]))
        print()


if __name__ == "__main__":
    main()
